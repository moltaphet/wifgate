// Regenerates src/abi.ts from the Foundry build output: `forge build` first, then `npm run abi`.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(
  readFileSync(join(here, "../../../contracts/out/WifGate.sol/WifGate.json"), "utf8"),
);
const abi = artifact.abi.filter((e) => e.type !== "constructor" || true);
writeFileSync(
  join(here, "../src/abi.ts"),
  `// Generated by scripts/gen-abi.mjs from contracts/out/WifGate.sol. Do not edit by hand.\nexport const wifGateAbi = ${JSON.stringify(abi, null, 2)} as const;\n`,
);
console.log(`wrote ${abi.length} ABI entries`);
